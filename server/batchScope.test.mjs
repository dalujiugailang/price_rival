import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { createDatabase } from './database.mjs';
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'batch-scope-'));
const file = path.join(dir, 'test.sqlite');
const context = { actor: { openId: 'test', name: '测试' } };
const batch = (id, type, activity, date = '2026-10-12') => ({ id, batchType: type, launchActivity: activity, date, competitivenessDate: date, operator: '测试', products: [{ ppv: 'overlap', jdPrice: 100 }], isCompetitivenessConfirmed: true });
let db = createDatabase(file);
try {
  db.createBatch(batch('legacy'), context);
  db.close();
  const old = new DatabaseSync(file);
  old.exec('DROP INDEX tracking_batches_one_confirmed_scope; CREATE UNIQUE INDEX tracking_batches_one_confirmed_date ON tracking_batches(channel_id, competitiveness_date) WHERE is_confirmed = 1 AND deleted_at IS NULL');
  old.close();
  db = createDatabase(file);
  assert.equal(db.getBatch('legacy').batchType, undefined);
  db.createBatch(batch('regular', 'regular'), context);
  db.createBatch(batch('launchA', 'launch', '小米发新'), context);
  db.createBatch(batch('launchB', 'launch', 'vivo发新'), context);
  assert.equal(db.listBatches().filter(b => b.isCompetitivenessConfirmed).length, 4);
  db.createBatch(batch('launchA2', 'launch', ' 小米发新 '), context);
  assert.equal(db.getBatch('launchA').isCompetitivenessConfirmed, false);
  assert.equal(db.getBatch('regular').isCompetitivenessConfirmed, true);
  assert.equal(db.getBatch('launchB').isCompetitivenessConfirmed, true);
  assert.equal(db.getBatch('legacy').isCompetitivenessConfirmed, true);
  db.createBatch(batch('launchUnnamed', 'launch', undefined), context);
  assert.equal(db.getBatch('launchUnnamed').isCompetitivenessConfirmed, true);
  db.importBatches([{ ...batch('regular2', 'regular'), confirmedAt: '9999-01-01' }, { ...batch('launchB2', 'launch', 'vivo发新'), confirmedAt: '9999-01-01' }], context);
  assert.equal(db.getBatch('regular').isCompetitivenessConfirmed, false);
  assert.equal(db.getBatch('launchB').isCompetitivenessConfirmed, false);
  assert.equal(db.getBatch('launchA2').isCompetitivenessConfirmed, true);
  db.close();
  db = createDatabase(file);
  assert.equal(db.listBatches().filter(b => b.isCompetitivenessConfirmed).length, 5);
  assert.equal(db.getBatch('launchA2').products[0].ppv, 'overlap');
} finally { db.close(); fs.rmSync(dir, { recursive: true, force: true }); }
console.log('PASS: legacy migration, independent confirmation, same-scope replacement, import, validation, restart and overlapping PPV');
