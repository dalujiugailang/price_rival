import assert from 'node:assert/strict';
import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
import PriceTimeline from './PriceTimeline';
import {CalculatedProduct,TrackingBatch} from '../types';
const p={ppv:'ONE-PERIOD-PPV',brand:'华为',newSeries:'Mate 80',oldModel:'华为 Mate 60',quoteVolume:0,recommendJdPrice:100,totalSubsidy:0,postJdHandPrice:100,tmPrice:0,tmSubsidyManual:0,tmHandPrice:0} as CalculatedProduct;
const batches=[{id:'A',date:'2026-10-01',products:[p]},{id:'B',date:'2026-10-02',products:[]}] as TrackingBatch[];
const html=renderToStaticMarkup(<PriceTimeline batches={batches} brand="华为" newSeries="Mate 80"/>);
assert.ok(html.includes('ONE-PERIOD-PPV'),'sparse PPVs appear even without a price in the final snapshot');
assert.ok(!html.includes('起始期')&&!html.includes('结束期')&&!html.includes('固定样本'));
assert.equal((html.match(/aria-label="京东天猫全历史价格迷你图"/g)||[]).length,3);
assert.ok(html.includes('1 / 1')&&html.includes('已显示全部'));
assert.ok(html.includes('缺失期平滑连线，不补数值'));
console.log('Timeline UI: complete sparse PPV history, three price views and no comparison-period controls passed.');
const {default:TimelineHistoryDetails}=await import('./TimelineHistoryDetails');
const {priceTimelinePoints}=await import('../utils/priceAnalysis');
const points=priceTimelinePoints(batches,p.ppv);
const detailHtml=renderToStaticMarkup(<TimelineHistoryDetails ppv={p.ppv} points={points}/>);
assert.ok(detailHtml.includes('2026-10-01')&&!detailHtml.includes('2026-10-02'),'only list periods containing the selected PPV');
assert.ok(detailHtml.includes('物品价差')&&detailHtml.includes('到手价差'));
assert.ok(!detailHtml.includes('<svg'),'chronological detail is a numeric table');
assert.ok(html.includes('详情'),'each timeline row provides a detail action');
console.log('Timeline details: saved-period records, chronological source and platform gaps passed.');
