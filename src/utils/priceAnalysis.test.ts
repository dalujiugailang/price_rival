import assert from 'node:assert/strict';
import {aggregate,comparePrices,indexPpv,value,advice} from './priceAnalysis';
import {CalculatedProduct,TrackingBatch} from '../types';
const product=(ppv:string,n:number,q=1)=>({ppv,brand:'苹果',quoteVolume:q,basePrice:1000,recommendJdPrice:n,totalSubsidy:20,postJdHandPrice:n+20,tmPrice:n+10,tmSubsidyManual:10,tmHandPrice:n+20,postMarginalProfit:.1,maxPriceByMargin:n+5} as CalculatedProduct);
const batch=(id:string,products:CalculatedProduct[])=>({id,date:'2026-10-20',marginBottomLine:.1,products} as TrackingBatch);
const a=batch('a',[product('P1',100,1),product('P2',200,3)]);
const b=batch('b',[{...product('P1',120,99),skuId:999,levelId:'changed'},product('P2',240,1),product('new',100)]);
assert.equal(comparePrices(a,b).filter(r=>r.a&&r.b).length,2,'SKU and grade do not change matching');
const agg=aggregate([a,b]);
assert.equal(agg.points[0].recommendJdPrice,175);
assert.equal(agg.points[1].recommendJdPrice,210,'uses baseline weights rather than period 2 volume');
assert.equal(agg.coverage,1);
assert.equal(Number(agg.points[1].postJdHandPrice)-Number(agg.points[0].postJdHandPrice),35);
const dup=batch('dup',[product('P1',1),product('P1',2),product('P2',3)]);
assert.equal(indexPpv(dup).rows.has('P1'),false);
assert.equal(comparePrices(a,dup).some(r=>r.ppv==='P1'),false);
assert.equal(aggregate([a,dup]).count,1);
assert.equal(aggregate([a,dup]).coverage,.75);
assert.equal(value({...product('P',1),tmPrice:0},'tmPrice'),null);
assert.equal(value({...product('P',1),totalSubsidy:0},'totalSubsidy'),0);
assert.equal(aggregate([batch('z',[product('P',1,0)])]).points[0].tmPrice,null);
assert.equal(advice(a)[0].type,'利润底线限制');
const rulesBatch={...a,restorePayload:{subsidyRules:[]} } as TrackingBatch;
const lossProduct={...product('loss',700),tmPrice:1200,basePrice:1000,ahsInput:0};
assert.equal(advice({...rulesBatch,products:[lossProduct]})[0].type,'亏损风险');
console.log('Price analysis: PPV matching, conflicts, fixed quotation weights, missing values, attribution and loss rules passed.');
const replaced={...a,products:a.products.map(p=>({...p,recommendJdPrice:p.recommendJdPrice+100,postJdHandPrice:p.postJdHandPrice+100}))};
assert.equal(aggregate([replaced]).points[0].recommendJdPrice,275,'a replaced snapshot must not reuse old cached values');
assert.equal(aggregate([a]).points[0].recommendJdPrice,175,'cached analysis must not mutate saved snapshots');

const {analysisHierarchy, analysisIdentity, matchesAnalysisScope, comparisonScope}=await import('./priceAnalysis');
const legacyHuawei={...product('H',100,1),brand:'Mate',oldModel:'华为 Mate 60',newSeries:'Mate 80',rawFields:{}};
const legacyOppo={...product('O',200,3),brand:'Find',oldModel:'OPPO Find X7',newSeries:'Find X8',rawFields:{}};
const legacyHuaweiOther={...product('H2',300,2),brand:'Pura',oldModel:'华为 Pura 70',newSeries:'Pura 80',rawFields:{}};
const explicitHuawei={...product('RAW',400),brand:'17系列',oldModel:'无前缀旧机',newSeries:'Mate 80',rawFields:{'BK_品牌名称':'华为'}};
const unknown={...product('UNKNOWN',500),brand:'17系列',oldModel:'无品牌型号',newSeries:'17系列',rawFields:{}};
const legacy=batch('legacy',[legacyHuawei,legacyOppo,legacyHuaweiOther,explicitHuawei,unknown]);
const hierarchy=analysisHierarchy([legacy]);
assert.deepEqual(new Set(hierarchy.keys()),new Set(['OPPO','华为']));
assert.deepEqual(hierarchy.get('华为'),['Mate 80','Pura 80']);
assert.deepEqual(hierarchy.get('OPPO'),['Find X8']);
assert.equal(analysisIdentity(legacyHuawei).brand,'华为');
assert.equal(analysisIdentity(unknown).brand,'','do not promote series names to brands');
assert.equal(matchesAnalysisScope(legacyOppo,'华为','Find X8'),false);
assert.equal(aggregate([legacy],'华为','Mate 80').count,2);
assert.equal(aggregate([legacy],'华为','Mate 80').points[0].recommendJdPrice,250);
assert.equal(legacyHuawei.brand,'Mate','analysis must not rewrite saved snapshots');
const baseline=batch('base',[{...legacyHuawei,quoteVolume:1},{...legacyOppo,quoteVolume:3}]);
const comparison=batch('comparison',[{...legacyHuawei,recommendJdPrice:120,quoteVolume:99},{...legacyOppo,recommendJdPrice:240,quoteVolume:1}]);
const scope=comparisonScope(comparison,baseline);
assert.equal(scope.rows[0].a?.recommendJdPrice,100);
assert.equal(scope.rows[0].b?.recommendJdPrice,120);
const scopeAgg=aggregate(scope.batches);
assert.equal(scopeAgg.points[0].recommendJdPrice,175);
assert.equal(scopeAgg.points[1].recommendJdPrice,210);
assert.equal(Number(scopeAgg.points[1].recommendJdPrice)-Number(scopeAgg.points[0].recommendJdPrice),35,'comparison minus baseline, using baseline weights');
console.log('Brand hierarchy, legacy recovery, series filtering and explicit baseline direction passed.');

const {priceTimelineCatalog,priceTimelinePoints}=await import('./priceAnalysis');
const early={...legacyHuawei,ppv:'TIMELINE',quoteVolume:0,totalSubsidy:0,tmPrice:0,tmHandPrice:0};
const late={...early,newSeries:'Mate 90',recommendJdPrice:180,tmPrice:160,tmHandPrice:160};
const oldOnly={...legacyHuawei,ppv:'OLD-ONLY'};
const history=[{...batch('T1',[early,oldOnly]),pricingTimestamp:'2026-10-01T10:00:00+08:00'},{...batch('T2',[]),pricingTimestamp:'2026-10-02T10:00:00+08:00'},{...batch('T3',[late]),pricingTimestamp:'2026-10-03T10:00:00+08:00'}];
assert.equal(priceTimelineCatalog(history).length,2,'include PPVs not shared by all periods');
const timeline=priceTimelinePoints(history,'TIMELINE');
assert.equal(timeline[0].recommendJdPrice,100,'zero quote volume does not exclude actual prices');
assert.equal(timeline[0].tmPrice,null,'missing competitor quote does not suppress JD price');
assert.equal(timeline[0].totalSubsidy,0,'a real zero subsidy remains zero');
assert.equal(timeline[1].recommendJdPrice,null,'missing period is a gap rather than a carried or zero price');
assert.equal(timeline[2].recommendJdPrice,180);
assert.equal(priceTimelineCatalog(history,'华为','Mate 90')[0].product.ppv,'TIMELINE','series membership in any period includes the complete PPV history');
assert.equal(priceTimelinePoints([history[2],history[0],history[1]],'TIMELINE')[0].recommendJdPrice,100,'history is ordered by pricing time');
console.log('Full-history PPV union, sparse periods, independent prices, zero volume and series changes passed.');
const {smoothPricePath}=await import('./priceAnalysis');
assert.equal(timeline[0].present,1);
assert.equal(timeline[1].present,0);
const smooth=smoothPricePath([{x:0,y:10},{x:10,y:20},{x:20,y:10},null,{x:40,y:5},{x:50,y:8}]);
assert.equal((smooth.match(/M/g)||[]).length,2,'smoothing must preserve a gap between observations');
assert.equal((smooth.match(/C/g)||[]).length,3);
assert.ok(!smooth.includes('NaN')&&!smooth.includes('Infinity'));
assert.equal(smoothPricePath([null,{x:5,y:12},null]),'M5.0,12.0');
console.log('Smooth interpolation retains observed points and does not bridge missing periods.');
assert.equal(advice(a)[0].owner,'我方定价决策');
assert.equal(advice({...rulesBatch,products:[lossProduct]})[0].owner,'分货+销售');
assert.equal(advice(batch('room',[{...product('room',100),maxPriceByMargin:200}])).length,0,'available pricing room produces no feedback');
const subsidyCase={...product('subsidy',120),tmPrice:110,postJdHandPrice:150,tmHandPrice:150};
assert.equal(advice(batch('equal-hand',[subsidyCase]))[0].owner,'京东换新渠道方','equal hand price still requires subsidy feedback');
assert.equal(advice(batch('better-hand',[{...subsidyCase,postJdHandPrice:151}])).length,0);
assert.equal(advice(batch('equal-item',[{...subsidyCase,recommendJdPrice:110}])).length,0,'item price must be strictly higher');
console.log('Advice routing and strict item / inclusive hand-price boundaries passed.');
